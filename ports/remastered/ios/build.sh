#!/bin/sh
# Build "Top Gear Rally Remastered" for the iPhone.
#   the games:  ports/remastered/link.sh, HOST=ios: Top Gear Rally (the cartridge's
#               data from your ROM built in) and Boss Rally (BRGlide.dll's data
#               built in), each one object behind its entry points, with the
#               multiplexer and the process (rm_main) in libgames.a
#   the disc:   Boss Rally's data track, from your disc image (or the tree's
#               reference/brally/data/disc), in the app as Resources/disc
#   the app:    the Swift host and the touch controls in Sources, an Xcode project
#               generated by xcodegen into build/remastered/ios-metal, the icon
#               from ports/remastered/icon.png, signed automatically
#
# Usage: ports/remastered/ios/build.sh [--rom FILE] [--bin FILE] [--sim] [--install [--device ID]]
#        ports/remastered/ios/build.sh --payload
#   --bin FILE   Boss Rally's disc image (default reference/brally/BossRally.BIN)
#   --payload    the app with none of the games' data and unsigned, for the release
#                builder (builder/build.sh): it adds the player's data (disc/ and
#                romdata.bin) and signs it (build/remastered/ios-payload)
#   --sim        build for the Simulator instead (build/remastered/ios-sim-metal)
#   --install    put it on the phone (devicectl's identifier or name with
#                --device; default: the first paired physical iPhone)
set -e
cd "$(dirname "$0")/../../.."
INSTALL=0
DEVICE=
SIM=
PAYLOAD=
BIN=reference/brally/BossRally.BIN
while [ $# -gt 0 ]; do
    case $1 in
        --rom) TGR_ROM=$2; export TGR_ROM; shift 2 ;;
        --bin) BIN=$2; shift 2 ;;
        --install) INSTALL=1; shift ;;
        --device) DEVICE=$2; shift 2 ;;
        --sim) SIM=1; shift ;;
        --payload) PAYLOAD=1; shift ;;
        *) echo "ios/build.sh: unknown argument $1" >&2; exit 2 ;;
    esac
done
OUT=build/remastered/ios-metal SDK=iphoneos DEST=generic/platform=iOS
if [ -n "$SIM" ]; then
    OUT=build/remastered/ios-sim-metal SDK=iphonesimulator
    DEST="generic/platform=iOS Simulator"
    TGR_IOS_SIM=1; export TGR_IOS_SIM
    INSTALL=0
fi
if [ -n "$PAYLOAD" ]; then
    OUT=build/remastered/ios-payload
    IMAGE=runtime ROMDATA=file; export IMAGE ROMDATA    # the data read from the app at start-up
    INSTALL=0
fi
PY=.venv/bin/python
[ -x $PY ] || PY=python3

# ---- Boss Rally's disc: the tree's data track, else the disc image's ----------------
DISC=reference/brally/data/disc
if [ ! -f $DISC/BRGlide.dll ]; then
    DISC=build/brally/macos-metal/extract/disc
    if [ ! -f $DISC/BRGlide.dll ]; then
        [ -f "$BIN" ] || { echo "ios/build.sh: no Boss Rally disc image at $BIN" >&2; exit 1; }
        mkdir -p $DISC
        $PY tools/brally/extract_disc.py "$BIN" $DISC
    fi
fi
mkdir -p $OUT
# the data track as the game's CD root, less the installer and the video
rm -rf $OUT/disc
if [ -n "$PAYLOAD" ]; then
    mkdir -p $OUT/disc                                  # the builder fills it
else
rsync -a --exclude 'brally.avi' --exclude '*.cab' --exclude '*.exe' --exclude '*.EXE' \
    --exclude '_INST32I.EX_' --exclude '_SETUP.DLL' --exclude 'dsetup*.dll' --exclude 'Msvcrt.dll' \
    --exclude 'BRD3D.dll' --exclude 'SETUP.INI' --exclude 'setup.*' --exclude 'Setup.BMP' \
    --exclude 'Autorun.inf' --exclude '*.url' --exclude 'layout.bin' \
    $DISC/ $OUT/disc/
fi

# ---- the games, the multiplexer and the process ------------------------------------
OUT=$OUT HOST=ios RENDER=metal CC=ports/remastered/ios/cc.sh GFLAG=-g0 DLL=$DISC/BRGlide.dll \
    ports/remastered/link.sh

# ---- the icon: one 1024-point image, no alpha (the asset catalog makes the rest) ------
IC=$OUT/Assets.xcassets/AppIcon.appiconset
rm -rf $OUT/Assets.xcassets && mkdir -p $IC
$PY -c "import sys; from PIL import Image; Image.open(sys.argv[1]).convert('RGB').resize((1024, 1024)).save(sys.argv[2])" \
    ports/remastered/icon.png $IC/icon.png
cat > $OUT/Assets.xcassets/Contents.json <<EOF
{ "info" : { "author" : "xcode", "version" : 1 } }
EOF
cat > $IC/Contents.json <<EOF
{
  "images" : [ { "filename" : "icon.png", "idiom" : "universal", "platform" : "ios", "size" : "1024x1024" } ],
  "info" : { "author" : "xcode", "version" : 1 }
}
EOF

# ---- the app ---------------------------------------------------------------------
xcodegen generate --quiet --spec ports/remastered/ios/project.yml --project $OUT --project-root $OUT
if [ -n "$PAYLOAD" ]; then
    SIGN="CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY="
else
    SIGN=-allowProvisioningUpdates
fi
xcodebuild -project $OUT/TopGearRallyRemastered.xcodeproj -scheme TopGearRallyRemastered -configuration Release \
    -destination "$DEST" -derivedDataPath $OUT/derived $SIGN \
    ARCHS=arm64 ONLY_ACTIVE_ARCH=NO -quiet build
APP="$OUT/derived/Build/Products/Release-$SDK/Top Gear Rally Remastered.app"
echo "built $APP"
[ $INSTALL = 1 ] || exit 0
if [ -z "$DEVICE" ]; then
    DEVICE=$(xcrun devicectl list devices 2>/dev/null | awk '/physical/ && /iPhone/ && /available/ { for (i = 1; i <= NF; i++) if ($i ~ /^[0-9A-F]{8}-[0-9A-F]{16}$/) { print $i; exit } }')
fi
[ -n "$DEVICE" ] || { echo "ios/build.sh: no paired iPhone found" >&2; exit 1; }
xcrun devicectl device install app --device "$DEVICE" "$APP"
