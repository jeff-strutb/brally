"""ports/common/models/texmat.csv (the Remastered material of every game texture,
by the FNV-1a hash of its RGBA8 large level) as a C table: writes
ports/brally/platform/light/light_texmat.h, the hashes sorted for a binary search."""
import sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
src = os.path.join(ROOT, 'ports/common/models/texmat.csv')
out = os.path.join(ROOT, 'ports/brally/platform/light/light_texmat.h')
rows = {}
for line in open(src):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    h, mat = line.split(',')[:2]
    rows[int(h, 16)] = mat
mats = sorted(set(rows.values()))
with open(out, 'w') as f:
    f.write('/* light_texmat.h: generated by ports/brally/tools/texmat_h.py from\n'
            ' * ports/common/models/texmat.csv (do not edit): the Remastered material of\n'
            ' * every game texture by the FNV-1a hash of its RGBA8 large level, sorted. */\n')
    f.write('#ifndef BR_LIGHT_TEXMAT_H\n#define BR_LIGHT_TEXMAT_H\n\n#include <stdint.h>\n\n')
    f.write('enum {\n' + ''.join('    LIGHT_MAT_%s,\n' % m.upper() for m in mats) + '    LIGHT_MAT_COUNT\n};\n')
    f.write('static const char *const k_light_mat_name[LIGHT_MAT_COUNT] = { %s };\n' % ', '.join('"%s"' % m for m in mats))
    f.write('static const struct { uint32_t hash; uint8_t mat; } k_light_texmat[%d] = {\n' % len(rows))
    for h in sorted(rows):
        f.write('    { 0x%08Xu, LIGHT_MAT_%s },\n' % (h, rows[h].upper()))
    f.write('};\n\n#endif\n')
print('wrote', out, len(rows), 'textures,', len(mats), 'materials')
